// Run with Node.js after editing the source tokens.
import { readFile, writeFile } from 'node:fs/promises';

const read = async (path) => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));
const cssName = (path) => '--' + path.replaceAll('.', '-');
const dimension = (value) => value.value + value.unit;
const color = (value) => {
  const channels = value.components.map((n) => Math.round(n * 255)).join(' ');
  return 'rgb(' + channels + ' / ' + (value.alpha ?? 1) + ')';
};
function declarations(tree, prefix = '') {
  const lines = [];
  for (const [key, item] of Object.entries(tree)) {
    const path = prefix ? prefix + '.' + key : key;
    if (!Object.hasOwn(item, '$value')) {
      lines.push(...declarations(item, path));
      continue;
    }
    const name = cssName(path);
    const v = item.$value;
    const add = (suffix, value) => lines.push('  ' + name + suffix + ': ' + value + ';');
    if (typeof v === 'string' && v.startsWith('{')) {
      add('', 'var(' + cssName(v.slice(1, -1)) + ')');
      continue;
    }
    switch (item.$type) {
      case 'color':
        add('', color(v));
        break;
      case 'dimension':
      case 'duration':
        add('', dimension(v));
        break;
      case 'fontFamily':
        add('', v.map((f) => (f.includes(' ') ? '"' + f + '"' : f)).join(', '));
        break;
      case 'typography':
        add('-size', v.fontSize.value / 16 + 'rem');
        add('-weight', v.fontWeight);
        add('-line', v.lineHeight);
        add('-tracking', v.letterSpacing.value / v.fontSize.value + 'em');
        add('-family', 'var(' + cssName(v.fontFamily.slice(1, -1)) + ')');
        break;
      case 'shadow':
        add(
          '',
          [v.offsetX, v.offsetY, v.blur, v.spread].map(dimension).join(' ') + ' ' + color(v.color),
        );
        break;
      default:
        throw new Error('Unsupported token ' + path);
    }
  }
  return lines;
}
const base = await read('../../tokens.json');
const dark = await read('../../themes/dark.json');
const sage = Object.keys(base.color.accent).map(
  (k) => '  --color-accent-' + k + ': var(--color-sage-' + k + ');',
);
const block = (selector, lines) => selector + ' {\n' + lines.join('\n') + '\n}\n';
const result =
  '/* Generated by build.mjs from Ondo tokens. */\n' +
  block(':root', declarations(base)) +
  block(':root[data-theme="dark"]', declarations(dark)) +
  block(':root[data-accent="sage"]', sage);
await writeFile(new URL('tokens.css', import.meta.url), result);
